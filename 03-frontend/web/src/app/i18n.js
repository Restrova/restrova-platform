export function normalizeLocale(locale) {
  return SUPPORTED_LOCALES.includes(locale) ? locale : DEFAULT_LOCALE;
}

export function directionForLocale(locale) {
  return localeMeta[normalizeLocale(locale)].direction;
}

export function translate(locale, key) {
  const dictionary = dictionaries[normalizeLocale(locale)];
  const value = key.split(".").reduce((current, part) => current?.[part], dictionary);
  return typeof value === "string" ? value : key;
}
